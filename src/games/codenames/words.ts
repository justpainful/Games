/**
 * يسحب `count` كلمة مختلفة.
 *
 * السحب بخلط نسخة لا بالاختيار العشوائي المتكرّر: الثاني قد يعيد الكلمة نفسها
 * فيخرج لوح فيه «قمر» مرّتين، وهو خلل لا يُرى إلا حين يقع في لعبة حقيقية.
 */
export function drawWords(count: number): string[] {
  const pool = [...WORDS]
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    const a = pool[i]
    const b = pool[j]
    if (a === undefined || b === undefined) continue
    pool[i] = b
    pool[j] = a
  }
  return pool.slice(0, Math.min(count, pool.length))
}

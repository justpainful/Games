    private static func spellings(count: Int) -> [LocalQuestion] {
        wordBank.shuffled().prefix(count).enumerated().map { index, word in
            let letters = word.map(String.init).joined(separator: " ")
            return LocalQuestion(id: "fakek-\(index)", prompt: word,
                                 lead: "اكتب حروفها مفصولة بمسافات", answers: [letters])
        }
    }

    private static func scrambles(count: Int) -> [LocalQuestion] {
        let usable = wordBank.filter { $0.count >= 4 }
        return usable.shuffled().prefix(count).enumerated().map { index, word in
            let letters = Array(word.map(String.init))
            var mixed = letters.shuffled()
            var attempts = 0
            while mixed == letters && attempts < 8 {
                mixed = letters.shuffled()
                attempts += 1
            }
            return LocalQuestion(id: "rakeb-\(index)", prompt: mixed.joined(separator: " "),
                                 lead: "أعد تركيب الحروف لتكوّن الكلمة", answers: [word])
        }
    }


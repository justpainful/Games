/// سؤال محلي واحد.
///
/// الأسئلة مضمّنة في التطبيق ولا تُجلب من الخادم: اللعب المنفرد يجب أن يعمل في
/// المصعد وفي الطائرة، وأي جولة تنتظر شبكة تتحوّل إلى شاشة تحميل بدل لعبة.
/// المجموعات هنا صغيرة عمدًا — تكفي جلسة منفردة، والمخزون الكامل يبقى للخادم.
struct LocalQuestion: Identifiable, Hashable, Sendable {
    let id: String
    /// النص الكبير المعروض: كلمة أو مسألة أو علم.
    let prompt: String
    /// سطر التعليمات فوق السؤال.
    let lead: String
    /// الإجابات المقبولة؛ الأولى هي التي تُعرض عند الكشف.
    let answers: [String]
    /// تلميحات تُكشف تباعًا مع مرور الوقت (التخمين).
    let hints: [String]
    /// لعبة الحروف: أي كلمة تبدأ بهذا الحرف مقبولة.
    let openingLetter: String?

    init(id: String,
         prompt: String,
         lead: String,
         answers: [String],
         hints: [String] = [],
         openingLetter: String? = nil) {
        self.id = id
        self.prompt = prompt
        self.lead = lead
        self.answers = answers
        self.hints = hints
        self.openingLetter = openingLetter
    }

    var shownAnswer: String { answers.first ?? "" }
}


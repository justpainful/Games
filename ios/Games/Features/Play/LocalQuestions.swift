    /// جولات لعبة واحدة، مخلوطة.
    static func rounds(for game: GameInfo, count: Int) -> [LocalQuestion] {
        switch game.id {
        case "asraa":  return speedWords(count: count)
        case "fakek":  return spellings(count: count)
        case "rakeb":  return scrambles(count: count)
        case "huroof": return letterRounds(count: count)
        case "event":  return Array((knowledge + capitals + continents + flags).shuffled().prefix(count))
        default:
            let pool = self.pool(for: game.id)
            return Array(pool.shuffled().prefix(count))
        }
    }

    /// هل الإجابة المكتوبة مقبولة؟
    static func matches(_ input: String, question: LocalQuestion) -> Bool {
        let typed = normalize(input)
        guard !typed.isEmpty else { return false }

        if let letter = question.openingLetter {
            let head = normalize(letter)
            if !head.isEmpty, typed.hasPrefix(head), typed.count >= 3, !typed.contains(" ") {
                return true
            }
        }

        for answer in question.answers {
            let expected = normalize(answer)
            if expected.isEmpty { continue }
            if typed == expected { return true }
            // «الرياض» و«رياض» إجابتان لنفس السؤال — أل التعريف ليست فرقًا في المعرفة
            if typed == "ال" + expected || expected == "ال" + typed { return true }
        }
        return false
    }

    /// تسوية النص العربي قبل المقارنة.
    ///
    /// اللاعب يكتب بسرعة تحت مؤقّت: يهمل الهمزة، ويخلط التاء المربوطة بالهاء،
    /// ويكتب الأرقام بالمشرقية. رفض هذه الإجابات ليس دقّة بل عقاب على السرعة.
    static func normalize(_ raw: String) -> String {
        var result = ""
        result.reserveCapacity(raw.count)
        var pendingSpace = false

        for character in raw {
            if character.isWhitespace {
                if !result.isEmpty { pendingSpace = true }
                continue
            }

            var mapped = ""
            switch character {
            case "أ", "إ", "آ", "ٱ", "ا":
                mapped = "ا"
            case "ى", "ئ", "ي":
                mapped = "ي"
            case "ة", "ه":
                mapped = "ه"
            case "ؤ":
                mapped = "و"
            case "ـ":
                mapped = ""
            case "\u{064B}"..."\u{0652}", "\u{0670}", "\u{0653}"..."\u{0655}":
                mapped = ""
            default:
                if character.isNumber, let value = character.wholeNumberValue, value >= 0 {
                    mapped = String(value)
                } else if character.isLetter {
                    mapped = character.lowercased()
                } else {
                    mapped = ""   // ترقيم وزخرفة لا تُقارَن
                }
            }

            if mapped.isEmpty { continue }
            if pendingSpace {
                result.append(" ")
                pendingSpace = false
            }
            result.append(mapped)
        }
        return result
    }


/**
 * رسائل تملك أزرارها بنفسها.
 *
 * ————————————————— لماذا وُجد هذا السجل —————————————————
 *
 * مستقبِل التفاعلات العام يفعل شيئين بكل ضغطة زر: يمرّرها للعبة الجارية، ثم
 * **يؤجّلها** بـ`deferUpdate` حتى لا يرى اللاعب «فشل التفاعل». وذلك صحيح لأزرار
 * اللعب، وقاتل لأزرار اللوحات التي تنتظر ضغطاتها بنفسها عبر
 * `awaitMessageComponent`: التفاعل المؤجَّل تفاعلٌ **مُجاب**، وديسكورد لا يقبل
 * فتح نافذة (modal) على تفاعل أُجيب. فيضغط صاحب اللوحة «نقاط الفوز» ولا يحدث
 * شيء، ولا خطأ يظهر لأن الفشل مبتلع.
 *
 * وقعت فعلًا في لوحة إعداد الفعالية. والعلاج أن تُعلن اللوحة ملكيتها لرسالتها،
 * فيتنحّى المستقبل العام عن أزرارها ويتركها لمن ينتظرها.
 */

const owned = new Set<string>()

/** تُعلن اللوحة أنها تتولّى أزرار هذه الرسالة بنفسها. */
export function holdPanel(messageId: string): void {
  owned.add(messageId)
}

/** تُعيدها إلى المسار العام حين تنتهي — تُنادى في `finally` دائمًا. */
export function releasePanel(messageId: string): void {
  owned.delete(messageId)
}

export function isPanel(messageId: string): boolean {
  return owned.has(messageId)
}
